"""Turn the curated Lightroom album (from frame-art-sync) into personal CleanFrame wallpapers.

Run with the frame-art-sync Python environment (Pillow, NumPy, cropcheck):
  ../frame-art-sync/.venv/bin/python scripts/import-lightroom-wallpapers.py [--count 30] [--measure]

Writes only to .local/wallpapers/ (ignored by Git). Then generate materials with
  CLEANFRAME_LOCAL_WALLPAPERS=1 node scripts/build-materials.mjs
"""
import argparse
import json
import shutil
import sys
from pathlib import Path

import numpy as np
from PIL import Image, ImageOps

ROOT = Path(__file__).resolve().parents[1]
OUT = ROOT / '.local/wallpapers/assets'
W, H = 1920, 1080
DOCK_BAND = (670, 910)  # the Dock glass covers roughly this band of the 1080 stage; the photo shows below it


def lum(rgb):
    a = rgb / 255.0
    a = np.where(a <= .04045, a / 12.92, ((a + .055) / 1.055) ** 2.4)
    return a @ np.array([.2126, .7152, .0722])


def params(photo):
    L = lum(np.asarray(photo, dtype=np.float64))
    tl, tr, br = L[40:200, 60:560].mean(), L[40:180, 1300:1880].mean(), L[860:1060, 1300:1880].mean()
    dock_p90 = float(np.quantile(L[700:1000, 96:1824], .9))
    # White interface text throughout: darker photo regions need little help,
    # lighter ones get the stronger 'mist' shading. Contrast is measured afterwards.
    return {
        'tone': 'light' if L.mean() > .18 or tl > .25 else 'dark',
        'ut': {'tr': 'light' if tr < .12 else 'mist', 'br': 'light' if br < .12 else 'mist'},
        'frostVeil': .3 if dock_p90 > .5 else .2,
        'listColumn': 0, 'dockQuiet': False, 'clockMist': bool(tl > .15),
    }, {'tl': round(float(tl), 3), 'tr': round(float(tr), 3), 'br': round(float(br), 3), 'dock_p90': round(dock_p90, 3)}


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument('--album', default=str(ROOT.parent / 'frame-art-sync/lightroom-album'))
    ap.add_argument('--tools', default=str(ROOT.parent / 'frame-art-sync'), help='folder with cropcheck.py')
    ap.add_argument('--count', type=int, default=30)
    ap.add_argument('--max-dock-share', type=float, default=0.38, help='skip photos whose subject sits mostly behind the Dock (an even spread is 0.22)')
    ap.add_argument('--measure', action='store_true', help='only report, write nothing')
    args = ap.parse_args()
    sys.path.insert(0, args.tools)
    import cropcheck

    album = sorted(Path(args.album).glob('*.jpg'), key=lambda p: p.stat().st_mtime, reverse=True)  # best first
    chosen, report = [], []
    for path in album:
        im = ImageOps.exif_transpose(Image.open(path)).convert('RGB')
        row = {'file': path.name}
        if im.width / im.height < 1.2:
            row['skip'] = 'portrait'; report.append(row); continue
        plan = cropcheck.plan_crop(im)
        if not plan['ok']:
            row['skip'] = 'subject would be cut'; report.append(row); continue
        photo = im.crop(plan['box']).resize((W, H), Image.LANCZOS)
        s = cropcheck.subject_map(photo)
        top, bottom = (int(round(s.shape[0] * y / H)) for y in DOCK_BAND)
        dock_share = float(s[top:bottom].sum() / max(s.sum(), 1e-9))
        row['dock_share'] = round(dock_share, 3)
        if dock_share > args.max_dock_share:
            row['skip'] = 'subject behind the Dock'; report.append(row); continue
        p, stats = params(photo)
        row.update(stats); report.append(row)
        if len(chosen) < args.count:
            chosen.append((path, photo, p))
    print(json.dumps({'album': len(album), 'eligible': sum('skip' not in r for r in report), 'chosen': len(chosen),
                      'skipped': {k: sum(r.get('skip') == k for r in report) for k in ('portrait', 'subject would be cut', 'subject behind the Dock')}}))
    if args.measure:
        print(json.dumps(report))
        return

    for sub in ('wallpapers', 'materials'):
        shutil.rmtree(OUT / sub, ignore_errors=True); (OUT / sub).mkdir(parents=True)
    sources, catalog = [], []
    for i, (path, photo, p) in enumerate(chosen, 1):
        wid = 'lr-' + ''.join(c for c in path.stem.lower() if c.isalnum())[:10]
        photo.save(OUT / 'wallpapers' / (wid + '.jpg'), 'JPEG', quality=90, subsampling=0)
        thumb = photo.resize((512, 288), Image.LANCZOS)
        thumb.save(OUT / 'wallpapers' / (wid + '-thumb.jpg'), 'JPEG', quality=85)
        entry = {'id': wid, 'name': 'Lightroom %02d' % i, 'src': 'assets/wallpapers/%s.jpg' % wid,
                 'thumb': 'assets/wallpapers/%s-thumb.jpg' % wid}
        sources.append(dict(entry, pos='50% 50%', tone=p['tone'], credit='Eigen foto', source='Lightroom'))
        catalog.append(dict(entry, **p))
    (OUT / 'wallpapers/SOURCES.json').write_text(json.dumps(sources, indent=2) + '\n')
    (OUT / 'wallpapers/catalog.js').write_text('/* Personal Lightroom gallery, generated by import-lightroom-wallpapers.py. */\n'
                                               'window.CleanFrameWallpapers = ' + json.dumps(catalog, indent=2) + ';\n')
    print('Wrote %d wallpapers to %s' % (len(chosen), OUT))


if __name__ == '__main__':
    main()
